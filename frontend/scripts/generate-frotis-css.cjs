// Generate only Frotis v2 utilities, theme and locally scoped Preflight.
// No host CSS or standalone reference HTML is rewritten.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const postcss = require('postcss');
const moduleDir = path.resolve(__dirname, '../src/features/analisis-frotis-v2');
const input = path.join(moduleDir, 'styles/tailwind.css');
const output = path.join(moduleDir, 'styles/module.css');
const cli = path.join(path.dirname(require.resolve('@tailwindcss/cli/package.json')), 'dist/index.mjs');
const raw = execFileSync(process.execPath, [cli, '-i', input], {
  cwd: path.resolve(__dirname, '..'), encoding: 'utf8',
});
const root = postcss.parse(raw);
// The host has unlayered element styles: keep the existing module precedence.
root.walkAtRules('layer', rule => {
  if (rule.nodes) rule.replaceWith(...rule.nodes);
  else rule.remove();
});
root.walkRules(rule => {
  if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  rule.selector = [...new Set(rule.selectors.map(selector =>
    /:root|:host/.test(selector) ? '.frotis-v2' : `.frotis-v2 ${selector}`,
  ))].join(', ');
});
// @property and @keyframes cannot be selector-scoped; give them a private name.
root.walkAtRules(/keyframes$/, rule => { rule.params = `frotis-v2-${rule.params}`; });
root.walkDecls(decl => {
  if (/^animation(?:-name)?$/.test(decl.prop) || decl.prop === '--animate-pulse') {
    decl.value = decl.value.replace(/\bpulse\b/g, 'frotis-v2-pulse');
  }
});
const css = '/* Generated by npm run styles:frotis; edit tokens_frotis_v2.css or tailwind.css. */\n'
  + root.toString().replaceAll('--tw-', '--frotis-v2-tw-').trimEnd() + '\n';
// Avoid unnecessary HMR cycles when output is unchanged.
if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== css) fs.writeFileSync(output, css);
