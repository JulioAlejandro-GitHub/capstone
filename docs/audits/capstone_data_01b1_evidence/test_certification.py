def prepared_and_plan(engine, population, version, seed):
    with engine.connect() as c:
        profiles = load_patient_profiles(c, version)
    optimization = optimize_patient_split(profiles, seed)
    assert optimization.winner.evaluation.valid
    assignments = optimization.winner.assignments
    assignment_rows = tuple(dict(id=uuid5(ASSIGNMENT_NAMESPACE, f"{version}:{r['id']}"),
        dataset_version_id=version, source_record_id=r['id'], clinical_identity_id=r['patient'],
        split_name=assignments[r['patient']], class_index=r['class_index'], class_name=r['class_name'],
        metadata='{}') for r in population['rows'])
    entries = tuple(MaterializationEntry(r['id'], r['patient'], assignments[r['patient']], r['class_name'],
        r['path'], Path(assignments[r['patient']])/r['class_name']/r['filename'], r['sha'])
        for r in population['rows'])
    record_digest = hashlib.sha256('\n'.join(
        f"{r['source_record_id']}|{r['clinical_identity_id']}|{r['split_name']}"
        for r in sorted(assignment_rows, key=lambda x: x['source_record_id'])).encode()).hexdigest()
    plan = MaterializationPlan(version, entries,
        optimization.winner.evaluation.canonical_assignment_digest, record_digest, 0, 'PRESERVE_SOURCE_FILENAME')
    return PreparedSplitGeneration(version, optimization, assignment_rows, {}), plan


