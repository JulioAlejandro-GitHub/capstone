def test_C_D_real_materializer_two_roots_ids_readback_idempotence_and_no_overwrite(engine, population):
    pairs = [prepared_and_plan(engine, population, v, seed)
             for v, seed in zip(population['versions'], (42, 43))]
    versions_root = population['root']/'data'/'malaria_dataset_versions'
    first_prepared, first_plan = pairs[0]
    install_fixture_assignments(engine, first_prepared, validated=True)
    first = materialize_dataset_version(engine, first_plan, versions_root)
    before = digest_tree(first.final_root)
    with engine.begin() as c:
        transition_dataset_version(c, first_plan.dataset_version_id, 'FROZEN')
        db_before = dict(DatasetVersionRepository(c).get(first_plan.dataset_version_id))
    second_prepared, second_plan = pairs[1]
    install_fixture_assignments(engine, second_prepared, validated=True)
    second = materialize_dataset_version(engine, second_plan, versions_root)
    assert first.final_root != second.final_root
    assert first.materialization_id != second.materialization_id
    for outcome, plan in ((first, first_plan), (second, second_plan)):
        assert outcome.final_root == versions_root/str(plan.dataset_version_id)
        assert {p.name for p in outcome.final_root.iterdir()} == {'train','val','test'}
        assert outcome.materialization_id == uuid5(MATERIALIZATION_NAMESPACE, f'{plan.dataset_version_id}:1')
        assert outcome.reconciliation.passed
        with engine.connect() as c:
            row = c.execute(text('SELECT * FROM dataset_materializations WHERE id=:id'),
                            dict(id=outcome.materialization_id)).mappings().one()
        assert row['relative_root'] == f'malaria_dataset_versions/{plan.dataset_version_id}'
        assert population['root']/'data'/row['relative_root'] == outcome.final_root
        assert row['status'] == 'READY' and row['reconciliation_status'] == 'PASS'
        assert row['record_count'] == len(population['rows'])
    retry = materialize_dataset_version(engine, second_plan, versions_root)
    assert retry.already_materialized and retry.materialization_id == second.materialization_id
    with pytest.raises(MaterializationError, match='MATERIALIZED_STATE_CONFLICT'):
        materialize_dataset_version(engine, replace(second_plan, patient_digest='0'*64), versions_root)
    assert digest_tree(first.final_root) == before
    with engine.connect() as c:
        assert dict(DatasetVersionRepository(c).get(first_plan.dataset_version_id)) == db_before
        assert audit_persisted_assignments(c, first_plan.dataset_version_id)['record_digest'] == first_plan.record_digest
    with engine.begin() as c:
        with pytest.raises(IntegrityError, match='FROZEN'):
            c.execute(text("UPDATE dataset_split_assignments SET split_name='val' WHERE dataset_version_id=:v"),
                      dict(v=first_plan.dataset_version_id))


def test_C_relative_root_assumes_canonical_parent(engine, population):
    prepared, plan = prepared_and_plan(engine, population, population['versions'][0], 42)
    install_fixture_assignments(engine, prepared, validated=True)
    output = population['root']/'noncanonical_parent'
    result = materialize_dataset_version(engine, plan, output)
    with engine.connect() as c:
        stored = c.execute(text('SELECT relative_root FROM dataset_materializations WHERE id=:id'),
                           dict(id=result.materialization_id)).scalar_one()
    assert stored == f'malaria_dataset_versions/{plan.dataset_version_id}'
    assert population['root']/'data'/stored != result.final_root


def test_D_existing_unregistered_destination_is_not_overwritten(engine, population):
    prepared, plan = prepared_and_plan(engine, population, population['versions'][0], 42)
    install_fixture_assignments(engine, prepared, validated=True)
    root = population['root']/'data'/'malaria_dataset_versions'
    final = root/str(plan.dataset_version_id)
    final.mkdir(parents=True)
    (final/'sentinel').write_bytes(b'keep')
    with pytest.raises(MaterializationError, match='FINAL_ROOT_EXISTS_WITHOUT_READY_PASS'):
        materialize_dataset_version(engine, plan, root)
    assert digest_tree(final) == {'sentinel': hashlib.sha256(b'keep').hexdigest()}
