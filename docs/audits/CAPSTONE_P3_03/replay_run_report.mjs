  response: 'training_summaries_response.json', response_sha256: createHash('sha256').update(payload).digest('hex'),
  response_count: response.count, response_limit: response.limit, processed_rows: rows.length,
  analysis_counts: group('analysis_title'), split_counts: group('metrics_split'), status_counts: group('status'),
  analysis_options_sorted: Object.keys(group('analysis_title')).sort((left, right) => left.localeCompare(right, 'es')),
  active_summaries: rows.filter(row => row.release_status === 'productive_stage2'),
