import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import ts from '../../../frontend/node_modules/typescript/lib/typescript.js';

const here = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(here, '../../../frontend/src/utils/runReport.ts');
const source = readFileSync(sourcePath, 'utf8');
const payload = readFileSync(resolve(here, 'training_summaries_response.json'), 'utf8');
const response = JSON.parse(payload);
const module = { exports: {} };
runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText,
  { exports: module.exports });
const { generateRunAutoAnalysis, resolveRunReportMetrics, resolveRunConfusion, normalizeConfusionMatrix } = module.exports;
const rows = response.items.map(run => {
  const counts = resolveRunConfusion(run);
  const metrics = resolveRunReportMetrics(run);
  const analysis = generateRunAutoAnalysis(run);
  const complete = Object.values(counts).every(value => value !== null);
  const total = complete ? Object.values(counts).reduce((sum, value) => sum + value, 0) : null;
  return {
    run_id: run.run_id, model_name: run.model_name, optimizer: run.optimizer, run_name: run.run_name,
    status: run.status, release_status: run.release_status, metrics_split: run.metrics_split,
    ...counts, total, recall: metrics.recall, specificity: metrics.specificity, f2: metrics.f2, auc: metrics.auc,
    threshold_displayed: run.scientific_parameters?.threshold ?? null,
    prediction_collapse_detected: run.prediction_collapse_detected,
    predicted_uninfected_fraction: total > 0 ? (counts.tn + counts.fn) / total : null,
    predicted_parasitized_fraction: total > 0 ? (counts.fp + counts.tp) / total : null,
    analysis_level: analysis.level, analysis_title: analysis.title, analysis_message: analysis.message,
  };
});
const keys = Object.keys(rows[0] ?? {});
const escapeCsv = value => value === null || value === undefined ? '' : `"${String(value).replaceAll('"', '""')}"`;
writeFileSync(resolve(here, 'auto_analysis_rows.csv'), [keys.join(','), ...rows.map(row => keys.map(key => escapeCsv(row[key])).join(','))].join('\n') + '\n');
const group = key => Object.fromEntries([...new Set(rows.map(row => row[key]))].map(value => [String(value), rows.filter(row => row[key] === value).length]));
